def main():
    assert len(RAW_QUESTIONS) == 100, f"Expected 100 questions, got {len(RAW_QUESTIONS)}"

    output_items = []
    seen_ids = set()
    seen_questions = set()

    for idx, (qid, question_text, correct_opt, distractors, reason) in enumerate(RAW_QUESTIONS):
        expected_id = f"kru-{2501 + idx}"
        assert qid == expected_id, f"ID mismatch at index {idx}: {qid} != {expected_id}"
        assert qid not in seen_ids, f"Duplicate ID: {qid}"
        seen_ids.add(qid)

        assert question_text not in seen_questions, f"Duplicate question text at {qid}"
        seen_questions.add(question_text)

        assert len(distractors) == 3, f"{qid} must have 3 distractors"
        assert correct_opt not in distractors, f"{qid} correct option in distractors"
        assert len(set(distractors)) == 3, f"{qid} has duplicate distractors"

        # Distribute correct answer evenly across indices 0, 1, 2, 3
        target_ans = (idx * 3 + (idx // 4)) % 4
        options = list(distractors)
        options.insert(target_ans, correct_opt)

        assert len(options) == 4
        assert options[target_ans] == correct_opt

        explanation = f"{correct_opt} — {reason}"
        assert explanation.strip(), f"Empty explanation at {qid}"

        item = {
            "id": qid,
            "category": "major",
            "categoryName": "วิชาเอกภาษาไทย",
            "majorSubject": "ภาษาไทย",
            "sourcePdf": "ชุดที่ 26: วิชาเอกภาษาไทย (ข้อ 2501-2600)",
            "question": question_text,
            "options": options,
            "answer": target_ans,
            "explanation": explanation,
        }
        output_items.append(item)

    out_path = os.path.join(os.path.dirname(__file__), "thai_set26.json")
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(output_items, f, ensure_ascii=False, indent=2)

    # Validation check on saved file
    with open(out_path, "r", encoding="utf-8") as f:
        loaded = json.load(f)

    assert len(loaded) == 100
    ans_counts = {0: 0, 1: 0, 2: 0, 3: 0}
    for i, item in enumerate(loaded):
        assert item["id"] == f"kru-{2501 + i}"
        assert len(item["options"]) == 4
        assert len(set(item["options"])) == 4
        assert item["answer"] in (0, 1, 2, 3)
        ans_counts[item["answer"]] += 1
        assert item["explanation"].startswith(item["options"][item["answer"]] + " — ")

    print(f"Successfully generated and validated {len(loaded)} questions at {out_path}")
    print(f"Answer index distribution: {ans_counts}")


if __name__ == "__main__":
    main()
